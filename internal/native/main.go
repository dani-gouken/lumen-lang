package native

import (
	"fmt"
	"strings"

	"github.com/dani-gouken/lumen/internal/runner"
	"github.com/dani-gouken/lumen/internal/vm"
)

// Main writes the main package of a program made by lumen native: it runs
// the program's bytecode, with its functions compiled to Go, as lumen run
// runs its source, with the limits of its project.
func Main(name string, chunk *vm.Chunk, limits runner.Limits) (string, error) {
	bytecode, err := vm.SerializeChunk(chunk)
	if err != nil {
		return "", err
	}
	var imports []string
	if usesCompiler(chunk) {
		// The natives of std.compiler are the compiler itself
		imports = append(imports, `_ "github.com/dani-gouken/lumen/internal/inspect"`)
	}
	var out strings.Builder
	out.WriteString("// Code generated by lumen native. DO NOT EDIT.\n\n")
	out.WriteString("package main\n\n")
	out.WriteString("import (\n\t\"fmt\"\n\t\"os\"\n\t\"runtime\"\n\n")
	out.WriteString("\t\"github.com/dani-gouken/lumen/internal/runner\"\n\t\"github.com/dani-gouken/lumen/internal/vm\"\n")
	for _, imported := range imports {
		fmt.Fprintf(&out, "\t%s\n", imported)
	}
	out.WriteString(")\n\n")
	// The program's bytecode, which the executable carries
	fmt.Fprintf(&out, "var program = []byte(%q)\n\n", bytecode)
	out.WriteString(`// A program runs on the thread it started on, as under lumen run: a C
// library may want every call made from the main thread
func init() {
	runtime.LockOSThread()
}

func main() {
	chunk, err := vm.DeserializeChunk(program)
	if err != nil {
		fmt.Fprintln(os.Stderr, "Error:", err)
		os.Exit(1)
	}
`)
	fmt.Fprintf(&out, "\tchunk.Compiled = vm.%s\n", Table(name))
	out.WriteString("\tself, err := os.Executable()\n\tif err != nil {\n\t\tself = os.Args[0]\n\t}\n")
	fmt.Fprintf(&out, "\tmachine := runner.Machine(runner.Limits{HeapMB: %d, MaxDepth: %d}, os.Args[1:], self, os.Exit)\n", limits.HeapMB, limits.MaxDepth)
	out.WriteString("\tresult, err := machine.Exec(chunk)\n\trunner.Finish(result, err, os.Exit)\n}\n")
	return out.String(), nil
}

// usesCompiler reports whether a program calls the natives of
// std.compiler.
func usesCompiler(chunk *vm.Chunk) bool {
	for _, name := range chunk.ExternNames {
		if strings.HasPrefix(name, "std.compiler.") {
			return true
		}
	}
	return false
}
