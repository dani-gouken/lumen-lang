// Package native writes the functions of a compiled program as Go, for
// lumen native.
//
// What it writes is a file of package vm (see internal/vm/compiled.go): a
// Go function for each function of the program it knows how to write, and
// a table of them by prototype for the program's main to give the chunk.
// Each does what the instruction loop does for the function's bytecode,
// instruction by instruction: the simple ones are written out, so that Go
// compiles a sum of two Ints to a sum; the others call the function of
// package vm that does them. A function with an instruction it does not
// know stays bytecode.
package native

import (
	"fmt"
	"math"
	"regexp"
	"strconv"
	"strings"

	"github.com/dani-gouken/lumen/internal/vm"
)

// Program is a program to write the functions of: its chunk, and a name
// that is a Go identifier, which its functions and their table are named
// with (Table).
type Program struct {
	Name  string
	Chunk *vm.Chunk
}

// Table is the name of the variable of package vm that holds the compiled
// functions of a program, by prototype: what its chunk is given as
// Compiled.
func Table(name string) string {
	return "Compiled" + name
}

// Result is the Go source of the programs' functions, and how many of them
// were compiled.
type Result struct {
	Source    string
	Compiled  int
	Frameless int // Of those compiled, how many have a frameless form too
	Total     int
}

// Generate writes the functions of programs as Go, in one file of package
// vm.
func Generate(programs ...Program) Result {
	var out strings.Builder
	out.WriteString("// Code generated by lumen native. DO NOT EDIT.\n\n")
	out.WriteString("package vm\n\n")
	out.WriteString("import (\n\t\"math\"\n\t\"unsafe\"\n)\n\n")
	out.WriteString("var _ = math.Mod\nvar _ = unsafe.Pointer(nil)\n\n")

	result := Result{}
	for _, program := range programs {
		chunk := program.Chunk
		compiled := make([]bool, len(chunk.Prototypes))
		for i := range chunk.Prototypes {
			compiled[i] = supported(chunk, i)
		}
		prefix := "compiled" + program.Name + "_"
		light := framelessFunctions(chunk, compiled)
		for i := range chunk.Prototypes {
			if compiled[i] {
				writeFunction(&out, chunk, i, compiled, light, prefix)
				result.Compiled++
			}
			if light[i] != nil {
				writeFrameless(&out, chunk, i, light, prefix)
				result.Frameless++
			}
		}
		result.Total += len(chunk.Prototypes)

		fmt.Fprintf(&out, "// %s is the functions of %s compiled to Go, by prototype.\n", Table(program.Name), program.Name)
		fmt.Fprintf(&out, "var %s = []CompiledFunc{\n", Table(program.Name))
		for i := range chunk.Prototypes {
			if compiled[i] {
				fmt.Fprintf(&out, "\t%s%d,\n", prefix, i)
			} else {
				out.WriteString("\tnil,\n")
			}
		}
		out.WriteString("}\n\n")
	}
	result.Source = out.String()
	return result
}

// longJumps are the instructions that follow a LONG prefix.
var longJumps = map[vm.OpCode]bool{vm.OpJMP32: true, vm.OpJMPIF32: true, vm.OpJMPIFNOT32: true, vm.OpTRY32: true}

// step is how many words an instruction takes: three for one with a LONG
// prefix, one more for each case of a SWITCH.
func step(code []vm.Instr, i int) int {
	switch code[i].Op {
	case vm.OpLONG:
		return 3
	case vm.OpSWITCH:
		return 1 + int(code[i].B)
	}
	return 1
}

// supported reports whether every instruction of a function can be
// compiled: all can, written as they are, but a word that is not where an
// instruction is expected.
func supported(chunk *vm.Chunk, index int) bool {
	p := chunk.Prototypes[index]
	code := chunk.Code[p.CodeStart : p.CodeStart+p.CodeSize]
	for i := 0; i < len(code); i += step(code, i) {
		switch op := code[i].Op; {
		case op == vm.OpLONG:
			if i+2 >= len(code) || !longJumps[code[i+1].Op] {
				return false
			}
		case op == vm.OpCASE || longJumps[op] || op > vm.LastOp:
			return false
		case op == vm.OpSWITCH:
			if i+int(code[i].B) >= len(code) {
				return false
			}
		}
	}
	return true
}

// targets are the instructions of a function something jumps to, a
// handler included; handlers are those of TRY32.
func targets(code []vm.Instr, start int) (map[int]bool, []int) {
	found := map[int]bool{}
	var handlers []int
	for i := 0; i < len(code); i += step(code, i) {
		instr := code[i]
		switch instr.Op {
		case vm.OpJMP:
			found[int(instr.A)] = true
		case vm.OpJMPIF, vm.OpJMPIFNOT:
			found[int(instr.B)] = true
		case vm.OpJNLT, vm.OpJNLE, vm.OpJNEQ, vm.OpJNNE,
			vm.OpJNLTI, vm.OpJNLEI, vm.OpJNGTI, vm.OpJNGEI, vm.OpJNEQI, vm.OpJNNEI,
			vm.OpJNLTK, vm.OpJNLEK, vm.OpJNGTK, vm.OpJNGEK, vm.OpJNEQK, vm.OpJNNEK, vm.OpJNTYPE:
			found[int(instr.C)] = true
		case vm.OpLONG:
			target := start + i + 3 + int(vm.DecodeOffset32(code[i+2]))
			found[target] = true
			if code[i+1].Op == vm.OpTRY32 {
				handlers = append(handlers, target)
			}
		case vm.OpSWITCH:
			found[int(instr.C)] = true
			for c := 1; c <= int(instr.B); c++ {
				found[int(code[i+c].B)] = true
			}
		}
	}
	return found, handlers
}

func writeFunction(out *strings.Builder, chunk *vm.Chunk, index int, compiled []bool, light []*frameless, prefix string) {
	p := chunk.Prototypes[index]
	code := chunk.Code[p.CodeStart : p.CodeStart+p.CodeSize]
	jumpedTo, handlers := targets(code, p.CodeStart)

	fmt.Fprintf(out, "// %s%d is %s.\n", prefix, index, p.Name)
	fmt.Fprintf(out, "func %s%d(vm *VM) (Value, error) {\n", prefix, index)
	out.WriteString("\tr := vm.regs\n\tkept := vm.kept()\n\tconsts := vm.chunk.Constants\n")
	out.WriteString("\t_, _, _ = r, kept, consts\n")
	var body strings.Builder
	w := &writer{out: &body, compiled: compiled, consts: chunk.Constants, registers: p.RegisterCount, code: code, start: p.CodeStart, prefix: prefix, proto: index, light: light}
	params, _ := signature(p.Signature, p.ArgCount)
	returns := make([]kind, len(chunk.Prototypes))
	for i, callee := range chunk.Prototypes {
		_, returns[i] = signature(callee.Signature, callee.ArgCount)
	}
	w.kinds, w.local = registerKinds(code, p.RegisterCount, params, chunk.Constants, returns)
	// The registers that are Go variables, declared before any label
	for k, is := range w.local {
		if !is {
			continue
		}
		if w.kinds[k] == floatKind {
			fmt.Fprintf(out, "\tvar f%d float64\n\t_ = f%d\n", k, k)
		} else {
			fmt.Fprintf(out, "\tvar i%d int64\n\t_ = i%d\n", k, k)
		}
	}
	w.bounds()
	// The arguments that are Go variables, from where the caller put them
	for k := 0; k < p.ArgCount && k < len(w.local); k++ {
		if w.local[k] {
			if w.kinds[k] == floatKind {
				w.line("f%d = floatOf(r[%d])", k, k)
			} else {
				w.line("i%d = intOf(r[%d])", k, k)
			}
		}
	}
	for i := 0; i < len(code); i += step(code, i) {
		pc := p.CodeStart + i
		if jumpedTo[pc] {
			fmt.Fprintf(&body, "L%d:\n", pc)
		}
		w.pc, w.instr = pc, code[i]
		w.instruction()
	}
	// Code that falls off its end is not written by the compiler; the
	// loop would stop there with nothing returned
	body.WriteString("\treturn NewNull(), nil\n")
	if len(handlers) == 0 {
		out.WriteString(body.String())
		out.WriteString("}\n\n")
		return
	}

	// A function that leaves handlers goes to one with what fails in it,
	// if the handler is its own: every failure goes through failed
	out.WriteString("\tbase := vm.frameCount\n\tvar failure error\n")
	out.WriteString(failing.ReplaceAllString(body.String(), "{ failure = $1; goto failed }$2"))
	out.WriteString("failed:\n\tif vm.handle(base, failure) {\n")
	w.out = out
	w.reload()
	out.WriteString("\t\tswitch vm.ip {\n")
	for _, h := range handlers {
		fmt.Fprintf(out, "\t\tcase %d:\n\t\t\tgoto L%d\n", h, h)
	}
	out.WriteString("\t\t}\n\t}\n\treturn NewNull(), failure\n}\n\n")
}

// writer writes one instruction.
// failing finds where a function returns a failure.
var failing = regexp.MustCompile(`return NewNull\(\), ([^;{}\n]+?)( }|\n|;)`)

type writer struct {
	frameless bool         // Writing the frameless form of a function
	proto     int          // The function being written
	light     []*frameless // The functions that have a frameless form
	kinds     []kind
	local     []bool
	prefix    string
	code      []vm.Instr
	start     int
	out       *strings.Builder
	pc        int
	instr     vm.Instr
	compiled  []bool
	consts    []vm.Value
	registers int
}

// bounds tells Go how many registers r has, once it is taken again from
// the VM, so that it checks no index of them after that.
func (w *writer) bounds() {
	if w.registers > 0 {
		w.line("_ = r[%d]", w.registers-1)
	}
}

// reload takes the registers again after what may have moved them.
func (w *writer) reload() {
	w.line("r = vm.regs")
	w.bounds()
}

// intConstant returns a constant of the chunk that is an Int.
func (w *writer) intConstant(index int) (int64, bool) {
	k := w.consts[index]
	if !k.IsInt() {
		return 0, false
	}
	return k.AsInt(), true
}

// floatConstant returns a constant that is a Float written as a literal:
// not NaN or an infinity.
func (w *writer) floatConstant(index int) (string, bool) {
	k := w.consts[index]
	if k.IsInt() || !k.IsNumber() {
		return "", false
	}
	x := k.AsNumber()
	if math.IsNaN(x) || math.IsInf(x, 0) {
		return "", false
	}
	return "float64(" + strconv.FormatFloat(x, 'g', -1, 64) + ")", true
}

// fastConstant writes, for arithmetic with a constant, the way through for
// an operand of the constant's own type, the number being in the code; it
// opens an else for every other operand, to be closed by the caller, and
// reports whether it did.
func (w *writer) fastConstant(A, B, C int) bool {
	op := w.instr.Op
	if k, ok := w.intConstant(C); ok {
		switch op {
		case vm.OpADDK, vm.OpSUBK:
			sign := "+"
			if op == vm.OpSUBK {
				sign = "-"
			}
			w.line("if a := r[%d]; a.IsInt() {", B)
			w.line("n := intOf(a) %s %d", sign, k)
			w.line("if n < MinInt || n > MaxInt { vm.ip = %d; return NewNull(), vm.runtimeError(\"integer overflow\") }", w.pc)
			w.line("r[%d] = NewInt(n)", A)
			w.line("} else {")
			return true
		case vm.OpMULK:
			w.line("if a := r[%d]; a.IsInt() {", B)
			w.line("product, fits := mulInts(intOf(a), %d)", k)
			w.line("if !fits { vm.ip = %d; return NewNull(), vm.runtimeError(\"integer overflow\") }", w.pc)
			w.line("r[%d] = NewInt(product)", A)
			w.line("} else {")
			return true
		case vm.OpDIVK, vm.OpMODK:
			// Neither by zero nor the smallest Int by -1: those the long
			// way, with their failures
			if k == 0 || k == -1 {
				return false
			}
			sign := "/"
			if op == vm.OpMODK {
				sign = "%"
			}
			w.line("if a := r[%d]; a.IsInt() {", B)
			w.line("r[%d] = NewInt(intOf(a) %s %d)", A, sign, k)
			w.line("} else {")
			return true
		}
		return false
	}
	if x, ok := w.floatConstant(C); ok && op != vm.OpMODK {
		sign := map[vm.OpCode]string{vm.OpADDK: "+", vm.OpSUBK: "-", vm.OpMULK: "*", vm.OpDIVK: "/"}[op]
		w.line("if a := r[%d]; a.IsNumber() {", B)
		w.line("r[%d] = NewNumber(floatOf(a) %s %s)", A, sign, x)
		w.line("} else {")
		return true
	}
	return false
}

func (w *writer) line(format string, args ...any) {
	w.out.WriteString("\t")
	fmt.Fprintf(w.out, format, args...)
	w.out.WriteString("\n")
}

// at makes the instruction the one errors and calls are reported at.
func (w *writer) at() {
	w.line("vm.ip = %d", w.pc)
}

// fail returns the error err holds, if it holds one.
func (w *writer) fail() string {
	return "if err != nil { return NewNull(), err }"
}

// jump goes to an instruction, letting the program be stopped on a jump
// back, as the loop does.
func (w *writer) jump(target int) string {
	if target <= w.pc && w.frameless {
		return fmt.Sprintf("{ if vm.interrupted.Load() || vm.outOfSteps() { return 0, vm.framelessStopped(%d, %d) }; goto L%d }", w.proto, w.pc, target)
	}
	if target <= w.pc {
		return fmt.Sprintf("{ if vm.interrupted.Load() || vm.outOfSteps() { vm.ip = %d; return NewNull(), vm.stopped() }; goto L%d }", w.pc, target)
	}
	return fmt.Sprintf("{ goto L%d }", target)
}

// instruction writes one instruction: on Go's numbers if what it works on
// is known to be numbers, as the instruction loop does it otherwise. The
// registers that are Go variables are put in the VM's registers for what
// is written the loop's way, and taken back from them.
func (w *writer) instruction() {
	if w.typed() {
		return
	}
	at := w.pc - w.start
	next := vm.Instr{}
	if at+1 < len(w.code) {
		next = w.code[at+1]
	}
	for _, k := range reads(w.instr, next) {
		if k < len(w.local) && w.local[k] {
			w.line("r[%d] = %s", k, w.boxed(k))
		}
	}
	w.general()
	if dest, ok := writes(w.instr); ok && dest < len(w.local) && w.local[dest] {
		if w.kinds[dest] == floatKind {
			w.line("f%d = floatOf(r[%d])", dest, dest)
		} else {
			w.line("i%d = intOf(r[%d])", dest, dest)
		}
	}
}

// general writes an instruction as the instruction loop does it.
func (w *writer) general() {
	in := w.instr
	A, B, C := int(in.A), int(in.B), int(in.C)
	instr := fmt.Sprintf("Instr{Op: %d, A: %d, B: %d, C: %d}", in.Op, in.A, in.B, in.C)

	switch in.Op {
	case vm.OpNOP:

	case vm.OpMOV:
		w.line("r[%d] = r[%d]", A, B)
	case vm.OpLOADK:
		w.line("r[%d] = Value(%d) // %s", A, uint64(w.consts[B]), w.consts[B].String())
	case vm.OpLOADNULL:
		w.line("r[%d] = valueNull", A)
	case vm.OpLOADBOOL:
		w.line("r[%d] = NewBool(%t)", A, B != 0)
	case vm.OpLOADI:
		w.line("r[%d] = NewInt(%d)", A, B)

	case vm.OpADD, vm.OpADDK:
		fast := in.Op == vm.OpADDK && w.fastConstant(A, B, C)
		w.line("{")
		w.line("a, b := r[%d], %s", B, w.second(C))
		w.line("if bothInts(a, b) {")
		w.line("sum := intOf(a) + intOf(b)")
		w.line("if sum < MinInt || sum > MaxInt { vm.ip = %d; return NewNull(), vm.runtimeError(\"integer overflow\") }", w.pc)
		w.line("r[%d] = NewInt(sum)", A)
		w.line("} else if x, y, ok := numbers(a, b); ok {")
		w.line("r[%d] = NewNumber(x + y)", A)
		w.line("} else {")
		w.at()
		w.line("str, err := vm.concatenate(a, b)")
		w.line("%s", w.fail())
		w.reload()
		w.line("r[%d] = str", A)
		w.line("vm.collectIfNeeded()")
		w.line("}")
		w.line("}")
		if fast {
			w.line("}")
		}

	case vm.OpSUB, vm.OpSUBK:
		fast := in.Op == vm.OpSUBK && w.fastConstant(A, B, C)
		w.line("{")
		w.line("a, b := r[%d], %s", B, w.second(C))
		w.line("if bothInts(a, b) {")
		w.line("diff := intOf(a) - intOf(b)")
		w.line("if diff < MinInt || diff > MaxInt { vm.ip = %d; return NewNull(), vm.runtimeError(\"integer overflow\") }", w.pc)
		w.line("r[%d] = NewInt(diff)", A)
		w.line("} else if x, y, ok := numbers(a, b); ok {")
		w.line("r[%d] = NewNumber(x - y)", A)
		w.line("} else { vm.ip = %d; return NewNull(), vm.arithmeticError(\"SUB\", \"-\", a, b) }", w.pc)
		w.line("}")
		if fast {
			w.line("}")
		}

	case vm.OpMUL, vm.OpMULK:
		fast := in.Op == vm.OpMULK && w.fastConstant(A, B, C)
		w.line("{")
		w.line("a, b := r[%d], %s", B, w.second(C))
		w.line("if bothInts(a, b) {")
		w.line("product, fits := mulInts(intOf(a), intOf(b))")
		w.line("if !fits { vm.ip = %d; return NewNull(), vm.runtimeError(\"integer overflow\") }", w.pc)
		w.line("r[%d] = NewInt(product)", A)
		w.line("} else if x, y, ok := numbers(a, b); ok {")
		w.line("r[%d] = NewNumber(x * y)", A)
		w.line("} else { vm.ip = %d; return NewNull(), vm.arithmeticError(\"MUL\", \"*\", a, b) }", w.pc)
		w.line("}")
		if fast {
			w.line("}")
		}

	case vm.OpDIV, vm.OpDIVK:
		fast := in.Op == vm.OpDIVK && w.fastConstant(A, B, C)
		w.line("{")
		w.line("a, b := r[%d], %s", B, w.second(C))
		w.line("if bothInts(a, b) {")
		w.line("if intOf(b) == 0 { vm.ip = %d; return NewNull(), vm.runtimeError(\"division by zero\") }", w.pc)
		w.at()
		w.line("quotient, err := vm.intResult(intOf(a) / intOf(b))")
		w.line("%s", w.fail())
		w.line("r[%d] = quotient", A)
		w.line("} else if x, y, ok := numbers(a, b); ok {")
		w.line("r[%d] = NewNumber(x / y)", A)
		w.line("} else { vm.ip = %d; return NewNull(), vm.arithmeticError(\"DIV\", \"/\", a, b) }", w.pc)
		w.line("}")
		if fast {
			w.line("}")
		}

	case vm.OpMOD, vm.OpMODK:
		fast := in.Op == vm.OpMODK && w.fastConstant(A, B, C)
		w.line("{")
		w.line("a, b := r[%d], %s", B, w.second(C))
		w.line("if bothInts(a, b) {")
		w.line("if intOf(b) == 0 { vm.ip = %d; return NewNull(), vm.runtimeError(\"division by zero\") }", w.pc)
		w.line("r[%d] = NewInt(intOf(a) %% intOf(b))", A)
		w.line("} else if x, y, ok := numbers(a, b); ok {")
		w.line("r[%d] = NewNumber(math.Mod(x, y))", A)
		w.line("} else { vm.ip = %d; return NewNull(), vm.arithmeticError(\"MOD\", \"%%\", a, b) }", w.pc)
		w.line("}")
		if fast {
			w.line("}")
		}

	case vm.OpADDI:
		w.line("{")
		w.line("a := r[%d]", B)
		w.line("if a.IsInt() {")
		w.line("sum := intOf(a) + %d", C)
		w.line("if sum > MaxInt { vm.ip = %d; return NewNull(), vm.runtimeError(\"integer overflow\") }", w.pc)
		w.line("r[%d] = NewInt(sum)", A)
		w.line("} else if a.IsNumber() {")
		w.line("r[%d] = NewNumber(floatOf(a) + %d)", A, C)
		w.line("} else {")
		w.at()
		w.line("result, err := vm.concatenate(a, NewInt(%d))", C)
		w.line("%s", w.fail())
		w.reload()
		w.line("r[%d] = result", A)
		w.line("}")
		w.line("}")

	case vm.OpSUBI:
		w.line("{")
		w.line("a := r[%d]", B)
		w.line("if a.IsNumber() {")
		w.line("r[%d] = NewNumber(floatOf(a) - %d)", A, C)
		w.line("} else if !a.IsInt() {")
		w.line("vm.ip = %d; return NewNull(), vm.arithmeticError(\"SUB\", \"-\", a, NewInt(%d))", w.pc, C)
		w.line("} else {")
		w.line("diff := intOf(a) - %d", C)
		w.line("if diff < MinInt { vm.ip = %d; return NewNull(), vm.runtimeError(\"integer overflow\") }", w.pc)
		w.line("r[%d] = NewInt(diff)", A)
		w.line("}")
		w.line("}")

	case vm.OpNEG:
		w.line("{")
		w.line("a := r[%d]", B)
		w.line("switch {")
		w.line("case a.IsInt():")
		w.at()
		w.line("negated, err := vm.intResult(-intOf(a))")
		w.line("%s", w.fail())
		w.line("r[%d] = negated", A)
		w.line("case a.IsNumber():")
		w.line("r[%d] = NewNumber(-floatOf(a))", A)
		w.line("default:")
		w.line("vm.ip = %d; return NewNull(), vm.runtimeError(\"NEG requires numeric operand, got: \" + a.String())", w.pc)
		w.line("}")
		w.line("}")

	case vm.OpNOT:
		w.line("if a := r[%d]; !a.IsBool() { vm.ip = %d; return NewNull(), vm.runtimeError(\"NOT requires boolean operand, got: \" + a.String()) } else { r[%d] = NewBool(a != valueTrue) }", B, w.pc, A)

	case vm.OpTONUM:
		w.line("{")
		w.line("a := r[%d]", B)
		w.line("switch {")
		w.line("case a.IsNumber():")
		w.line("r[%d] = a", A)
		w.line("case a.IsInt():")
		w.line("r[%d] = NewNumber(float64(intOf(a)))", A)
		w.line("default:")
		w.line("vm.ip = %d; return NewNull(), vm.runtimeError(\"TONUM requires int or number, got: \" + a.String())", w.pc)
		w.line("}")
		w.line("}")

	case vm.OpEQ:
		w.line("r[%d] = NewBool(sameValue(r[%d], r[%d]))", A, B, C)
	case vm.OpNE:
		w.line("r[%d] = NewBool(!sameValue(r[%d], r[%d]))", A, B, C)
	case vm.OpLT, vm.OpLE, vm.OpGT, vm.OpGE:
		symbol := map[vm.OpCode]string{vm.OpLT: "<", vm.OpLE: "<=", vm.OpGT: ">", vm.OpGE: ">="}[in.Op]
		w.line("{")
		w.line("a, b := r[%d], r[%d]", B, C)
		w.line("if bothInts(a, b) {")
		w.line("r[%d] = NewBool(intOf(a) %s intOf(b))", A, symbol)
		w.line("} else {")
		w.at()
		w.line("result, err := vm.compare(OpCode(%d), a, b)", in.Op)
		w.line("%s", w.fail())
		w.line("r[%d] = NewBool(result)", A)
		w.line("}")
		w.line("}")

	case vm.OpJMP:
		w.line("%s", w.jump(A))
	case vm.OpJMPIF:
		w.line("if r[%d] == valueTrue %s", A, w.jump(B))
	case vm.OpJMPIFNOT:
		w.line("if r[%d] == valueFalse %s", A, w.jump(B))

	case vm.OpJNLT, vm.OpJNLE:
		symbol, test := "<", vm.OpLT
		if in.Op == vm.OpJNLE {
			symbol, test = "<=", vm.OpLE
		}
		w.line("{")
		w.line("a, b := r[%d], r[%d]", A, B)
		w.line("holds := false")
		w.line("if bothInts(a, b) {")
		w.line("holds = intOf(a) %s intOf(b)", symbol)
		w.line("} else {")
		w.at()
		w.line("result, err := vm.compare(OpCode(%d), a, b)", test)
		w.line("%s", w.fail())
		w.line("holds = result")
		w.line("}")
		w.line("if !holds %s", w.jump(C))
		w.line("}")

	case vm.OpJNEQ:
		w.line("if !sameValue(r[%d], r[%d]) %s", A, B, w.jump(C))
	case vm.OpJNNE:
		w.line("if sameValue(r[%d], r[%d]) %s", A, B, w.jump(C))

	case vm.OpJNLTI, vm.OpJNLEI, vm.OpJNGTI, vm.OpJNGEI, vm.OpJNEQI, vm.OpJNNEI:
		symbol := map[vm.OpCode]string{vm.OpJNLTI: "<", vm.OpJNLEI: "<=", vm.OpJNGTI: ">", vm.OpJNGEI: ">=", vm.OpJNEQI: "==", vm.OpJNNEI: "!="}[in.Op]
		w.line("{")
		w.line("a := r[%d]", A)
		w.line("holds := false")
		w.line("if a.IsInt() {")
		w.line("holds = intOf(a) %s %d", symbol, B)
		w.line("} else {")
		w.at()
		w.line("result, err := vm.testAgainst(OpCode(%d), a, NewInt(%d))", in.Op, B)
		w.line("%s", w.fail())
		w.line("holds = result")
		w.line("}")
		w.line("if !holds %s", w.jump(C))
		w.line("}")

	case vm.OpJNLTK, vm.OpJNLEK, vm.OpJNGTK, vm.OpJNGEK, vm.OpJNEQK, vm.OpJNNEK:
		symbol := map[vm.OpCode]string{vm.OpJNLTK: "<", vm.OpJNLEK: "<=", vm.OpJNGTK: ">", vm.OpJNGEK: ">=", vm.OpJNEQK: "==", vm.OpJNNEK: "!="}[in.Op]
		ordered := in.Op != vm.OpJNEQK && in.Op != vm.OpJNNEK
		w.line("{")
		w.line("a, k := r[%d], consts[%d]", A, B)
		w.line("holds := false")
		if n, ok := w.intConstant(B); ok {
			w.line("if a.IsInt() {")
			w.line("holds = intOf(a) %s %d", symbol, n)
		} else if x, ok := w.floatConstant(B); ok && ordered {
			w.line("if a.IsNumber() {")
			w.line("holds = floatOf(a) %s %s", symbol, x)
			w.line("} else if bothInts(a, k) {")
			w.line("holds = intOf(a) %s intOf(k)", symbol)
		} else {
			w.line("if bothInts(a, k) {")
			w.line("holds = intOf(a) %s intOf(k)", symbol)
		}
		if ordered {
			w.line("} else if x, y, ok := numbers(a, k); ok {")
			w.line("holds = x %s y", symbol)
		}
		w.line("} else {")
		w.at()
		w.line("result, err := vm.testAgainst(againstConstant[OpCode(%d)], a, k)", in.Op)
		w.line("%s", w.fail())
		w.line("holds = result")
		w.line("}")
		w.line("if !holds %s", w.jump(C))
		w.line("}")

	case vm.OpCALLK:
		if w.framelessCall() {
			return
		}
		first, last := A+1, A+1+B
		w.line("{")
		w.at()
		if C < len(w.compiled) && w.compiled[C] {
			// A compiled function of this chunk: the lighter way in and out
			w.line("callee := kept.funcs[%d]", C)
			w.line("if callee == 0 {")
			w.line("made, err := vm.functionObject(vm.chunk, kept.funcs, %d)", C)
			w.line("%s", w.fail())
			w.line("callee = made")
			w.line("}")
			w.line("if vm.interrupted.Load() || vm.outOfSteps() { return NewNull(), vm.stopped() }")
			w.line("if err := vm.enterCompiledCall((*FunctionObj)(unsafe.Pointer(header(callee))), %d, %d); err != nil { return NewNull(), err }", first, last)
			w.line("result, err := %s%d(vm)", w.prefix, C)
			w.line("%s", w.fail())
			w.line("vm.leaveCompiledCall()")
		} else {
			w.line("callee, err := vm.compiledCallee(kept, %d)", C)
			w.line("%s", w.fail())
			w.line("if vm.interrupted.Load() || vm.outOfSteps() { return NewNull(), vm.stopped() }")
			w.line("if err := vm.enter(callee, r[%d:%d:%d]); err != nil { return NewNull(), err }", first, last, last)
			w.line("result, err := vm.run(vm.frameCount)")
			w.line("%s", w.fail())
			w.line("vm.leave()")
		}
		w.reload()
		w.line("r[0] = result")
		w.line("}")

	case vm.OpCALLX:
		w.at()
		w.line("if err := vm.compiledCALLX(kept, %s); err != nil { return NewNull(), err }", instr)
		w.reload()

	case vm.OpRET:
		w.line("{")
		w.line("result := r[%d]", A)
		w.line("if len(vm.stk.open) > 0 { vm.closeUpvalues(vm.base) }")
		w.line("return result, nil")
		w.line("}")

	case vm.OpNEWOBJ:
		w.at()
		w.line("if err := vm.compiledNEWOBJ(kept, %d, %s); err != nil { return NewNull(), err }", w.pc, instr)
	case vm.OpGETFIELD:
		w.at()
		w.line("if err := vm.compiledGETFIELD(kept, %d, %s); err != nil { return NewNull(), err }", w.pc, instr)
	case vm.OpSETFIELD:
		w.at()
		w.line("if err := vm.compiledSETFIELD(kept, %d, %s); err != nil { return NewNull(), err }", w.pc, instr)
	case vm.OpNEWSTR:
		w.at()
		w.line("if err := vm.compiledNEWSTR(kept, %s); err != nil { return NewNull(), err }", instr)
	case vm.OpGETINDEX:
		w.at()
		w.line("if err := vm.compiledGETINDEX(%s); err != nil { return NewNull(), err }", instr)
		w.reload()
	case vm.OpSETELEM:
		w.at()
		w.line("if err := vm.compiledSETELEM(%s); err != nil { return NewNull(), err }", instr)
	case vm.OpARRLEN:
		w.at()
		w.line("if err := vm.compiledARRLEN(%s); err != nil { return NewNull(), err }", instr)

	case vm.OpTOINT:
		w.at()
		w.line("if err := vm.compiledTOINT(%s); err != nil { return NewNull(), err }", instr)
	case vm.OpBAND, vm.OpBOR, vm.OpBXOR, vm.OpSHL, vm.OpSHR:
		w.at()
		w.line("if err := vm.compiledBITS(%s); err != nil { return NewNull(), err }", instr)

	case vm.OpLONG:
		jump := w.code[w.pc-w.start+1]
		target := w.pc + 3 + int(vm.DecodeOffset32(w.code[w.pc-w.start+2]))
		switch jump.Op {
		case vm.OpTRY32:
			w.line("vm.compiledTRY(%d)", target)
		case vm.OpJMP32:
			w.line("%s", w.jump(target))
		case vm.OpJMPIF32:
			w.line("if r[%d] == valueTrue %s", jump.A, w.jump(target))
		case vm.OpJMPIFNOT32:
			w.line("if r[%d] == valueFalse %s", jump.A, w.jump(target))
		}

	case vm.OpSWITCH:
		w.line("switch kept.caseOf(vm.chunk, %d, &kept.fields[%d], r[%d]) {", w.pc, w.pc, A)
		seen := map[int]bool{}
		cases := append([]int{}, C)
		for c := 1; c <= B; c++ {
			cases = append(cases, int(w.code[w.pc-w.start+c].B))
		}
		for _, target := range cases {
			if seen[target] {
				continue
			}
			seen[target] = true
			w.line("case %d: %s", target, w.jump(target))
		}
		w.line("}")
		w.line("return NewNull(), vm.runtimeError(\"SWITCH: no case\")")

	case vm.OpISTYPE:
		w.line("r[%d] = NewBool(isOfType(r[%d], &kept.fields[%d], vm.chunk.StringPool[intOf(consts[%d])]))", A, B, w.pc, C)
	case vm.OpJNTYPE:
		w.line("if !isOfType(r[%d], &kept.fields[%d], vm.chunk.StringPool[intOf(consts[%d])]) %s", A, w.pc, B, w.jump(C))

	case vm.OpCALL:
		w.at()
		w.line("if err := vm.compiledCALL(%s); err != nil { return NewNull(), err }", instr)
		w.reload()
	case vm.OpCALLM:
		w.at()
		w.line("if err := vm.compiledCALLM(kept, %d, %s); err != nil { return NewNull(), err }", w.pc, instr)
		w.reload()
	case vm.OpGETMETHOD:
		w.at()
		w.line("if err := vm.compiledGETMETHOD(kept, %d, %s); err != nil { return NewNull(), err }", w.pc, instr)
	case vm.OpONCE:
		w.at()
		w.line("if err := vm.compiledONCE(kept, %s); err != nil { return NewNull(), err }", instr)
		w.reload()

	case vm.OpNEWFUNC:
		w.at()
		w.line("if err := vm.compiledNEWFUNC(kept, %s); err != nil { return NewNull(), err }", instr)
	case vm.OpNEWEXFUNC, vm.OpCAPLOCAL, vm.OpCAPUPVAL, vm.OpLDCAP, vm.OpSTCAP,
		vm.OpNEWARRAY, vm.OpSETINDEX, vm.OpARRPUSH, vm.OpHASFIELD, vm.OpDELFIELD:
		name := map[vm.OpCode]string{
			vm.OpNEWEXFUNC: "NEWEXFUNC", vm.OpCAPLOCAL: "CAPLOCAL", vm.OpCAPUPVAL: "CAPUPVAL", vm.OpLDCAP: "LDCAP", vm.OpSTCAP: "STCAP",
			vm.OpNEWARRAY: "NEWARRAY", vm.OpSETINDEX: "SETINDEX", vm.OpARRPUSH: "ARRPUSH", vm.OpHASFIELD: "HASFIELD", vm.OpDELFIELD: "DELFIELD",
		}[in.Op]
		w.at()
		w.line("if err := vm.compiled%s(%s); err != nil { return NewNull(), err }", name, instr)
	case vm.OpCLOSEUP:
		w.line("vm.compiledCLOSEUP(%s)", instr)
	case vm.OpGC:
		w.line("vm.CollectGarbage()")
	case vm.OpENDTRY:
		w.at()
		w.line("if err := vm.compiledENDTRY(); err != nil { return NewNull(), err }")
	case vm.OpRETHROW:
		w.at()
		w.line("return NewNull(), vm.compiledRETHROW()")

	default:
		panic(fmt.Sprintf("native: %v is not written", in.Op))
	}
}

// second is the second operand of arithmetic: a register, or for the
// forms with a constant, the constant.
func (w *writer) second(c int) string {
	switch w.instr.Op {
	case vm.OpADDK, vm.OpSUBK, vm.OpMULK, vm.OpDIVK, vm.OpMODK:
		return fmt.Sprintf("consts[%d]", c)
	}
	return fmt.Sprintf("r[%d]", c)
}
